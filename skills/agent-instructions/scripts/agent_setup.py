def split_frontmatter(text: str) -> Tuple[Optional[List[str]], str]:
    lines = text.lstrip("\ufeff").replace("\r\n", "\n").split("\n")
    if lines[0].rstrip() != "---":
        return None, "\n".join(lines)
    for index in range(1, len(lines)):
        if lines[index].rstrip() in ("---", "..."):
            return lines[1:index], "\n".join(lines[index + 1:])
    raise FrontmatterError("the frontmatter that opens on line 1 never closes with ---")


def closing_double_quote(value: str) -> Optional[int]:
    index = 1
    while index < len(value):
        if value[index] == "\\":
            index += 2
            continue
        if value[index] == '"':
            return index
        index += 1
    return None


def reject_trailing_text(rest: str, line_number: int) -> None:
    if rest.strip() and not rest.strip().startswith("#"):
        raise FrontmatterError(f"line {line_number}: unexpected text after the closing quote")


def parse_yaml_scalar(raw: str, line_number: int, in_flow: bool = False) -> str:
    value = raw.strip()
    if value.startswith('"'):
        closing = closing_double_quote(value)
        if closing is None:
            raise FrontmatterError(f"line {line_number}: the double quote never closes")
        reject_trailing_text(value[closing + 1:], line_number)
        try:
            return json.loads(value[:closing + 1])
        except ValueError:
            raise FrontmatterError(f"line {line_number}: {value[:closing + 1]} uses an escape this reader does not support")
    if value.startswith("'"):
        characters, index = [], 1
        while index < len(value):
            if value[index] == "'":
                if value[index + 1:index + 2] == "'":
                    characters.append("'")
                    index += 2
                    continue
                reject_trailing_text(value[index + 1:], line_number)
                return "".join(characters)
            characters.append(value[index])
            index += 1
        raise FrontmatterError(f"line {line_number}: the single quote never closes")
    bare = re.split(r"[ \t]#", value, maxsplit=1)[0].strip()
    if bare[:1] and bare[0] in YAML_RESERVED_STARTS:
        raise FrontmatterError(f"line {line_number}: {bare} starts with {bare[0]}, which YAML does not read as text; quote it")
    if ": " in bare or bare.endswith(":"):
        raise FrontmatterError(f"line {line_number}: {bare} contains a colon that YAML reads as a key; quote it")
    if in_flow and any(character in bare for character in "{}[]"):
        raise FrontmatterError(f"line {line_number}: {bare} contains a brace or bracket inside [ ]; quote it")
    return bare


def parse_flow_list(raw: str, line_number: int) -> List[str]:
    value = raw.strip()
    closing = matching_bracket(value)
    if closing is None:
        raise FrontmatterError(f"line {line_number}: the [ list never closes on the same line")
    reject_trailing_text(value[closing + 1:], line_number)
    items = split_top_level(value[1:closing], quotes=True)
    return [parse_yaml_scalar(item, line_number, in_flow=True) for item in items if item.strip()]


def matching_bracket(value: str) -> Optional[int]:
    depth, quote, index = 0, None, 0
    while index < len(value):
        character = value[index]
        if quote:
            if character == "\\" and quote == '"':
                index += 2
                continue
            if character == quote:
                quote = None
        elif character in "\"'":
            quote = character
        elif character == "[":
            depth += 1
        elif character == "]":
            depth -= 1
            if depth == 0:
                return index
        index += 1
    return None


def block_list(lines: List[str], index: int, key: str) -> Tuple[List[str], int, Optional[str]]:
    items = []
    while index < len(lines):
        line = lines[index]
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            index += 1
            continue
        item = LIST_ITEM.match(line)
        if not item:
            if line[:1] in (" ", "\t"):
                return items, index, f"line {index + 2}: `{key}:` holds something other than a list of strings"
            break
        try:
            items.append(parse_yaml_scalar(item.group(1) or "", index + 2))
        except FrontmatterError as error:
            return items, index + 1, str(error)
        index += 1
    return items, index, None


def frontmatter_fields(lines: List[str]) -> dict:
    fields = {}
    index = 0
    while index < len(lines):
        match = FRONTMATTER_KEY.match(lines[index])
        index += 1
        if not match or match.group(1) not in STRING_FIELDS:
            continue
        key, inline = match.group(1), (match.group(2) or "").strip()
        if inline and not inline.startswith("#"):
            try:
                fields[key] = parse_flow_list(inline, index + 1) if inline.startswith("[") else parse_yaml_scalar(inline, index + 1)
            except FrontmatterError:
                if key == "paths":
                    raise
            continue
        items, index, problem = block_list(lines, index, key)
        if problem and key == "paths":
            raise FrontmatterError(problem)
        if not problem:
            fields[key] = items
    return fields


def rule_globs(value) -> List[str]:
    if value is None or value == "":
        return []
    if isinstance(value, str):
        return [part.strip() for part in split_top_level(value, quotes=False) if part.strip()]
    globs = []
    for item in value:
        parts = split_top_level(item, quotes=False)
        if len(parts) > 1:
            raise FrontmatterError(f"the glob {item} has a comma outside braces, which comma-separated targets read as two globs; list each glob separately")
        if item.strip():
            globs.append(item.strip())
    return globs


def parse_rule(root: Path, source: str, owned: bool) -> Rule:
    text = read_text(root / source)
    name = posixpath.basename(source)[:-len(".md")]
    try:
        frontmatter, body = split_frontmatter(text)
        fields = frontmatter_fields(frontmatter) if frontmatter is not None else {}
        globs = rule_globs(fields.get("paths"))
        for pattern in globs:
            expand_braces(pattern)
    except FrontmatterError as error:
        return Rule(name, source, text, [], None, None, text, str(error), owned)
    description = fields.get("description") if isinstance(fields.get("description"), str) else None
    exclude_agent = fields.get("excludeAgent") if isinstance(fields.get("excludeAgent"), str) else None
    return Rule(name, source, text, globs, description or None, exclude_agent or None, body.lstrip("\n"), None, owned)


def is_owned(path: str, owned: List[str]) -> bool:
    return any(path == entry.rstrip("/") or (entry.endswith("/") and path.startswith(entry)) for entry in owned)


def read_rules(root: Path, rules_dir: str, owned: List[str]) -> Tuple[List[Rule], List[str]]:
    directory = root / rules_dir
    if not directory.is_dir():
        return [], []
    rules, subdirectories = [], []
    for entry in sorted(os.listdir(directory)):
        relative = f"{rules_dir}/{entry}"
        if (directory / entry).is_dir():
            if not is_owned(relative + "/", owned):
                subdirectories.append(relative)
            continue
        if entry.endswith(".md") and (directory / entry).is_file():
            rules.append(parse_rule(root, relative, is_owned(relative, owned)))
    return rules, subdirectories


FENCE = re.compile(r"^ {0,3}(`{3,}|~{3,})")
INLINE_CODE = re.compile(r"(`+)(?!`).+?(?<!`)\1(?!`)", re.S)
INLINE_LINK = re.compile(r"(!?\[(?:[^\[\]]|\[[^\]]*\])*\]\(\s*<?)([^)\s>]+)(>?(?:\s+(?:\"[^\"]*\"|'[^']*'))?\s*\))")
REFERENCE_DEFINITION = re.compile(r"^( {0,3}\[(?!\^)[^\]]+\]:[ \t]*<?)([^\s>]+)", re.M)
EXTERNAL_TARGET = re.compile(r"^(?:[a-zA-Z][a-zA-Z0-9+.-]*:|//)")
HEADING = re.compile(r"^ {0,3}#{1,6}[ \t]+(.*?)[ \t]*$")
TITLE = re.compile(r"^ {0,3}#[ \t]+(.*?)[ \t]*$")
ATTRIBUTE_ID = re.compile(r"[ \t]*\{:?[ \t]*#([\w-]+)[^}]*\}[ \t]*$")
HTML_ID = re.compile(r"<[a-zA-Z][^>]*?\s(?:id|name)\s*=\s*[\"']([^\"']+)[\"']")
IMPORT_REFERENCE = re.compile(r"(?<![\w@`])@((?:\.{1,2}/)?[\w.-]+(?:/[\w.-]+)*)")
HTML_COMMENT = re.compile(r"<!--.*?-->", re.S)


def classify_fenced_lines(text: str):
    fence = None
    for line in text.splitlines(keepends=True):
        if fence is None:
            opening = FENCE.match(line)
            if opening:
                fence = opening.group(1)
            yield line, bool(opening)
            continue
        closing = line.strip()
        if closing and set(closing) == {fence[0]} and len(closing) >= len(fence):
            fence = None
        yield line, True


def inline_segments(text: str) -> List[Tuple[bool, str]]:
    segments, position = [], 0
    for match in INLINE_CODE.finditer(text):
        if match.start() > position:
            segments.append((False, text[position:match.start()]))
        segments.append((True, match.group(0)))
        position = match.end()
    if position < len(text):
        segments.append((False, text[position:]))
    return segments


def markdown_segments(text: str) -> List[Tuple[bool, str]]:
    segments, prose = [], []
    for line, fenced in classify_fenced_lines(text):
        if fenced:
            segments.extend(inline_segments("".join(prose)))
            prose = []
            segments.append((True, line))
        else:
            prose.append(line)
    segments.extend(inline_segments("".join(prose)))
    return segments


def masked_code(text: str) -> str:
    return "".join(re.sub(r"[^\n]", " ", segment) if is_code else segment for is_code, segment in markdown_segments(text))


def link_matches(text: str) -> List[re.Match]:
    masked = masked_code(text)
    return list(INLINE_LINK.finditer(masked)) + list(REFERENCE_DEFINITION.finditer(masked))


def link_targets(text: str) -> List[str]:
    return [match.group(2) for match in link_matches(text) if not match.group(1).startswith("!")]


def markdown_title(text: str) -> Optional[str]:
    for line, fenced in classify_fenced_lines(text):
        match = None if fenced else TITLE.match(line.rstrip("\r\n"))
        if match:
            return re.sub(r"[ \t]+#+$", "", match.group(1)).strip() or None
    return None


def heading_slug(text: str) -> str:
    text = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"<[^>]+>", "", text).lower()
    return "".join(character for character in text if character in " -_" or unicodedata.category(character)[0] in "LNM").replace(" ", "-")


def markdown_anchors(text: str) -> set:
    anchors, seen = set(), {}
    for line, fenced in classify_fenced_lines(text):
        match = None if fenced else HEADING.match(line.rstrip("\r\n"))
        if not match:
            continue
        content = re.sub(r"(?:^|[ \t]+)#+[ \t]*$", "", match.group(1))
        explicit = ATTRIBUTE_ID.search(content)
        if explicit:
            anchors.add(explicit.group(1).lower())
            content = content[:explicit.start()]
        slug = heading_slug(content)
        anchors.add(f"{slug}-{seen[slug]}" if slug in seen else slug)
        seen[slug] = seen.get(slug, 0) + 1
    anchors.update(identifier.lower() for identifier in HTML_ID.findall(text))
    return anchors


def resolve_link(source: str, path_part: str) -> Optional[str]:
    if path_part.startswith("/"):
        return normalize_relative(path_part.lstrip("/") or ".")
    return normalize_relative(posixpath.join(posixpath.dirname(source), path_part))


def rebased_target(target: str, source_directory: str, output_directory: str) -> str:
    if EXTERNAL_TARGET.match(target) or target.startswith(("#", "/")):
        return target
    path_part, separator, anchor = target.partition("#")
    resolved = posixpath.normpath(posixpath.join(source_directory, path_part))
    rebased = posixpath.relpath(resolved, output_directory or ".")
    if path_part.endswith("/") and not rebased.endswith("/"):
        rebased += "/"
    return rebased + separator + anchor


def rebase_links(body: str, source_directory: str, output_directory: str) -> str:
    if source_directory == output_directory:
        return body
    replacements = sorted(((match.start(2), match.end(2), match.group(2)) for match in link_matches(body)), reverse=True)
    for start, end, target in replacements:
        body = body[:start] + rebased_target(target, source_directory, output_directory) + body[end:]
    return body


def marker_line(rule: Rule) -> str:
    return f"{GENERATED_MARKER_PREFIX}{rule.source}. Edit that file, then run {GENERATE_COMMAND}. -->"


def is_generated(text: str) -> bool:
    try:
        _, body = split_frontmatter(text)
    except FrontmatterError:
        return False
    first = next((line for line in body.split("\n") if line.strip()), "")
    return first.startswith(GENERATED_MARKER_PREFIX)


PLAIN_YAML_TEXT = re.compile(r"^[A-Za-z0-9][A-Za-z0-9 _.,()/+'-]*$")


def yaml_text(value: str) -> str:
    return value if PLAIN_YAML_TEXT.match(value) and not value.endswith(" ") else json.dumps(value, ensure_ascii=False)


def joined_globs(rule: Rule, keys: dict) -> str:
    return keys.get("separator", ",").join(rule.expanded_globs)


def generated_document(header: List[str], rule: Rule, output_path: str) -> str:
    body = rebase_links(rule.body, posixpath.dirname(rule.source), posixpath.dirname(output_path)).rstrip("\n") + "\n"
    frontmatter = ["---", *header, "---", ""] if header else []
    return "\n".join(frontmatter + [marker_line(rule), "", ""]) + body


def cursor_mdc(rule: Rule, target: RuleTarget, output_path: str) -> str:
    keys = target.keys
    header = [f"{keys.get('description', 'description')}: {yaml_text(rule.summary)}"]
    if rule.has_paths:
        header += [f"{keys.get('globs', 'globs')}: {joined_globs(rule, keys)}", f"{keys.get('always_apply', 'alwaysApply')}: false"]
    else:
        header.append(f"{keys.get('always_apply', 'alwaysApply')}: true")
    return generated_document(header, rule, output_path)


def copilot_applyto(rule: Rule, target: RuleTarget, output_path: str) -> str:
    keys = target.keys
    apply_to = joined_globs(rule, keys) if rule.has_paths else keys.get("all_files", "**")
    header = [f"{keys.get('apply_to', 'applyTo')}: {json.dumps(apply_to)}"]
    if rule.exclude_agent:
        header.append(f"{keys.get('exclude_agent', 'excludeAgent')}: {json.dumps(rule.exclude_agent)}")
    return generated_document(header, rule, output_path)


def trigger_globs(rule: Rule, target: RuleTarget, output_path: str) -> str:
    keys = target.keys
    trigger = keys.get("trigger", "trigger")
    if not rule.has_paths:
        return generated_document([f"{trigger}: {keys.get('always_trigger', 'always_on')}"], rule, output_path)
    globs = joined_globs(rule, keys)
    value = json.dumps(globs) if keys.get("quote_globs") else globs
    return generated_document([f"{trigger}: {keys.get('glob_trigger', 'glob')}", f"{keys.get('globs', 'globs')}: {value}"], rule, output_path)


def kiro_filematch(rule: Rule, target: RuleTarget, output_path: str) -> str:
    keys = target.keys
    inclusion = keys.get("inclusion", "inclusion")
    if not rule.has_paths:
        return generated_document([f"{inclusion}: always"], rule, output_path)
    globs = rule.expanded_globs
    pattern = json.dumps(globs[0]) if len(globs) == 1 else "[" + ", ".join(json.dumps(candidate) for candidate in globs) + "]"
    return generated_document([f"{inclusion}: fileMatch", f"{keys.get('pattern', 'fileMatchPattern')}: {pattern}"], rule, output_path)


def cline_paths(rule: Rule, target: RuleTarget, output_path: str) -> str:
    if not rule.has_paths:
        return generated_document([], rule, output_path)
    header = [f"{target.keys.get('paths', 'paths')}:"] + [f"  - {json.dumps(candidate)}" for candidate in rule.expanded_globs]
    return generated_document(header, rule, output_path)


RULE_FILE_FORMATTERS: Dict[str, Callable[[Rule, RuleTarget, str], str]] = {
    "cursor-mdc": cursor_mdc,
    "copilot-applyto": copilot_applyto,
    "trigger-globs": trigger_globs,
    "kiro-filematch": kiro_filematch,
    "cline-paths": cline_paths,
}
LINK_FORMAT = "claude-symlink"
CODERABBIT_FORMAT = "coderabbit-filepatterns"
KNOWN_FORMATS = set(RULE_FILE_FORMATTERS) | {LINK_FORMAT, CODERABBIT_FORMAT}


def rule_error_message(rule: Rule) -> str:
    return f"{rule.source}: cannot read its frontmatter ({rule.error}); Claude Code then loads the rule in every session. Write paths: as a YAML list of quoted globs."


def exclude_agent_problem(rule: Rule, tool: Tool) -> Optional[str]:
    allowed = tool.rules.keys.get("exclude_agent_values", [])
    if rule.exclude_agent and allowed and rule.exclude_agent not in allowed:
        return f"{rule.source}: excludeAgent is {rule.exclude_agent!r}; {tool.name} accepts {', '.join(allowed)}."
    return None


def plan_generation(root: Path, registry: Registry, config: Config, rules: List[Rule]) -> GenerationPlan:
    plan = GenerationPlan()
    plan.problems.extend(Problem(rule_error_message(rule)) for rule in rules if rule.error and not rule.owned)
    erroneous = {rule.name for rule in rules if rule.error}
    sources = [rule for rule in rules if not rule.error and not rule.owned]
    expected: Dict[str, Tuple[str, str, str]] = {}
    coderabbit_targets = []
    enabled = target_tools(registry, config)
    for tool in enabled:
        if tool.rules is None or tool.rules.format is None:
            if tool.rules is not None and sources:
                plan.notes.append(f"{tool.name}: no confirmed format for path rules in {tool.rules.directory} yet, so nothing is generated; it reads AGENTS.md ({tool.docs}).")
            continue
        rule_format = tool.rules.format
        if rule_format not in KNOWN_FORMATS:
            raise UsageError(f"{tool.id} uses the rule format {rule_format!r}, which this agent_setup.py has no formatter for; update the script or remove {tool.id} from targets")
        if rule_format == LINK_FORMAT:
            continue
        if rule_format == CODERABBIT_FORMAT:
            coderabbit_targets.append(tool)
            continue
        formatter = RULE_FILE_FORMATTERS[rule_format]
        for rule in sources:
            problem = exclude_agent_problem(rule, tool)
            if problem:
                plan.problems.append(Problem(problem))
                continue
            output = f"{tool.rules.directory}/{rule.name}{tool.rules.extension}"
            content = formatter(rule, tool.rules, output)
            if output in expected and expected[output][0] != content:
                raise UsageError(f"{expected[output][1]} and {tool.id} would write different content to {output}; give one of them another directory in the registry")
            expected[output] = (content, tool.id, rule.source)
    for output, (content, _, source) in expected.items():
        plan_output(root, output, content, source, plan)
    plan_pruning(root, enabled, expected, erroneous, plan)
    if coderabbit_targets and not erroneous:
        plan_coderabbit(root, coderabbit_targets[0].rules, sources, config, plan)
    plan.problems = unique_problems(plan.problems)
    return plan


def unique_problems(problems: List[Problem]) -> List[Problem]:
    seen, kept = set(), []
    for problem in problems:
        if problem.message not in seen:
            seen.add(problem.message)
            kept.append(problem)
    return kept


def plan_output(root: Path, output: str, content: str, source: str, plan: GenerationPlan) -> None:
    path = root / output
    plan.outputs.append(output)
    parent = path.parent
    while parent != root:
        if os.path.lexists(parent) and not parent.is_dir():
            plan.problems.append(Problem(f"{relative_to(root, parent)} is a file, so {output} cannot be generated from {source}: move that file's content into AGENTS.md or a rule, then delete it."))
            return
        parent = parent.parent
    if not os.path.lexists(path):
        plan.changes.append(Change("create", output, content, source))
        return
    if path.is_symlink() or not path.is_file():
        plan.problems.append(Problem(f"{output} is a symlink or directory, and {source} would generate a file there: remove it or rename the rule."))
        return
    existing = read_text(path)
    if not is_generated(existing):
        plan.problems.append(Problem(f"{output} is hand-written, and {source} would generate a file with the same name: rename one of them; {output} was left alone."))
        return
    if existing != content:
        plan.changes.append(Change("update", output, content, source))


def plan_pruning(root: Path, enabled: List[Tool], expected: dict, erroneous: set, plan: GenerationPlan) -> None:
    locations = unique((tool.rules.directory, tool.rules.extension) for tool in enabled if tool.rules and tool.rules.format in RULE_FILE_FORMATTERS)
    for directory, extension in locations:
        folder = root / directory
        if not folder.is_dir():
            continue
        for entry in sorted(os.listdir(folder)):
            output = f"{directory}/{entry}"
            path = folder / entry
            if not entry.endswith(extension) or output in expected or path.is_symlink() or not path.is_file():
                continue
            if entry[:-len(extension)] in erroneous or not is_generated(read_text(path)):
                continue
            source = generated_source(read_text(path))
            plan.changes.append(Change("delete", output, None, source))


def generated_source(text: str) -> str:
    match = re.search(re.escape(GENERATED_MARKER_PREFIX) + r"(\S+?)\. ", text)
    return match.group(1) if match else "a rule"


