    def tool(self, tool_id: str) -> Tool:
        for tool in self.tools:
            if tool.id == tool_id:
                return tool
        raise UsageError(f"unknown tool {tool_id!r}; the registry knows {', '.join(tool.id for tool in self.tools)}")

    def in_categories(self, categories) -> List[Tool]:
        return [tool for tool in self.tools if tool.category in categories]


