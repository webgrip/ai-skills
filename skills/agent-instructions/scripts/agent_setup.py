def unique(values) -> list:
    return list(dict.fromkeys(values))


def as_tuple(value) -> tuple:
    if value is None:
        return ()
    if isinstance(value, str):
        return (value,)
    return tuple(value)


def read_text(path: Path) -> str:
    try:
        with open(path, encoding="utf-8", errors="replace", newline="") as handle:
            return handle.read()
    except OSError:
        return ""


def write_file(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as handle:
        handle.write(content)


def relative_to(root: Path, path: Path) -> str:
    return path.relative_to(root).as_posix()


def normalize_relative(path: str) -> Optional[str]:
    normalized = posixpath.normpath(path)
    if normalized == ".." or normalized.startswith("../") or normalized.startswith("/"):
        return None
    return normalized


def positive_ratio(value) -> float:
    try:
        ratio = float(value)
    except (TypeError, ValueError):
        raise argparse.ArgumentTypeError(f"{value!r} is not a number of bytes per token")
    if isinstance(value, bool) or not math.isfinite(ratio) or ratio <= 0:
        raise argparse.ArgumentTypeError(f"{value!r} must be a finite number above 0 bytes per token")
    return ratio


def load_registry(path: Path) -> Registry:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except OSError as error:
        raise UsageError(f"cannot read the tool registry {path}: {error.strerror}")
    except ValueError as error:
        raise UsageError(f"the tool registry {path} is not valid JSON: {error}")
    tools = [registry_tool(path, entry) for entry in data.get("tools", [])]
    identifiers = [tool.id for tool in tools]
    duplicates = sorted({identifier for identifier in identifiers if identifiers.count(identifier) > 1})
    if duplicates:
        raise UsageError(f"{path}: tool ids must be unique, these repeat: {', '.join(duplicates)}")
    if ALWAYS_TARGETED not in identifiers:
        raise UsageError(f"{path}: the registry must define the {ALWAYS_TARGETED} tool")
    missing_defaults = [key for key in CONFIG_KEYS if key != "targets" and key not in data.get("defaults", {})]
    if missing_defaults:
        raise UsageError(f"{path}: defaults lack {', '.join(missing_defaults)}")
    return Registry(
        tools=tuple(tools),
        defaults=dict(data["defaults"]),
        nested_instruction_names=as_tuple(data.get("nested_instruction_names")),
        flagged_files=as_tuple(data.get("flagged_files")),
        docs_sites=as_tuple(data.get("docs_sites")),
        walk_skip=frozenset(data.get("walk_skip", [])),
    )


def registry_tool(path: Path, entry: dict) -> Tool:
    missing = [key for key in REQUIRED_TOOL_KEYS if key not in entry]
    if missing:
        raise UsageError(f"{path}: tool {entry.get('id', '?')} lacks {', '.join(missing)}")
    if entry["category"] not in CATEGORIES:
        raise UsageError(f"{path}: tool {entry['id']} has category {entry['category']!r}; use one of {', '.join(CATEGORIES)}")
    for detector in entry["detect"]:
        if isinstance(detector, dict):
            try:
                re.compile(detector.get("pattern", ""))
            except re.error as error:
                raise UsageError(f"{path}: tool {entry['id']} has an invalid detect pattern: {error}")
    rules = entry["rules"]
    target = None
    if rules is not None:
        target = RuleTarget(rules.get("format"), rules.get("dir"), as_tuple(rules.get("also_dirs")), rules.get("ext"), dict(rules.get("keys") or {}))
    return Tool(
        id=entry["id"],
        name=entry["name"],
        category=entry["category"],
        detect=tuple(entry["detect"]),
        instructions=as_tuple(entry["instructions"]),
        rules=target,
        skills_dirs=as_tuple(entry["skills_dir"]),
        mcp_configs=as_tuple(entry["mcp_config"]),
        setup_files=as_tuple(entry["setup_file"]),
        ignore_files=as_tuple(entry.get("ignore_file")),
        hooks_files=as_tuple(entry.get("hooks_file")),
        reads_hooks_from=as_tuple(entry.get("reads_hooks_from")),
        owns=as_tuple(entry.get("owns")),
        note=entry.get("note"),
        docs=entry["docs"],
    )


def resolve_registry(argument: Optional[str]) -> Registry:
    if argument:
        return load_registry(Path(argument))
    for candidate in REGISTRY_CANDIDATES:
        if candidate.is_file():
            return load_registry(candidate)
    raise UsageError("cannot find targets.json in ../assets or next to agent_setup.py; pass --registry")


def resolve_root(argument: str) -> Path:
    root = Path(argument).resolve()
    if not root.is_dir():
        raise UsageError(f"{argument} is not a directory")
    return root


def detect_entry(root: Path, entry) -> List[str]:
    if isinstance(entry, dict):
        candidates = detect_entry(root, entry.get("file", ""))
        return [name for name in candidates if (root / name).is_file() and re.search(entry.get("pattern", ""), read_text(root / name))]
    if any(character in entry for character in "*?["):
        return sorted(relative_to(root, Path(match)) for match in glob.glob(os.path.join(glob.escape(str(root)), entry)))
    if entry.endswith("/"):
        return [entry] if (root / entry).is_dir() else []
    return [entry] if os.path.lexists(root / entry) else []


def tool_evidence(root: Path, tool: Tool) -> List[str]:
    return unique(match for entry in tool.detect for match in detect_entry(root, entry))


def detected_targets(root: Path, registry: Registry) -> List[str]:
    found = [tool.id for tool in registry.in_categories(TARGET_CATEGORIES) if tool_evidence(root, tool)]
    return unique([ALWAYS_TARGETED] + found)


def owned_paths(root: Path, registry: Registry) -> List[str]:
    return unique(path for tool in registry.tools if tool.owns and tool_evidence(root, tool) for path in tool.owns)


def config_path(key: str, value) -> str:
    if not isinstance(value, str) or not value.strip():
        raise UsageError(f"{CONFIG_FILE}: {key} must be a relative path")
    normalized = normalize_relative(value.strip().rstrip("/"))
    if normalized is None or normalized == ".":
        raise UsageError(f"{CONFIG_FILE}: {key} must be a path inside the repository, not {value!r}")
    return normalized


def config_count(key: str, value, allow_none: bool = False) -> Optional[int]:
    if value is None and allow_none:
        return None
    if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
        raise UsageError(f"{CONFIG_FILE}: {key} must be a whole number above 0{' or null' if allow_none else ''}, not {value!r}")
    return value


def config_targets(registry: Registry, value) -> List[str]:
    if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
        raise UsageError(f"{CONFIG_FILE}: targets must be a list of tool ids")
    for item in value:
        registry.tool(item)
    return unique(value)


def load_config(root: Path, registry: Registry) -> Config:
    path = root / CONFIG_FILE
    values = {}
    if path.is_file():
        try:
            values = json.loads(read_text(path))
        except ValueError as error:
            raise UsageError(f"{CONFIG_FILE} is not valid JSON: {error}")
        if not isinstance(values, dict):
            raise UsageError(f"{CONFIG_FILE} must hold a JSON object")
        unknown = sorted(set(values) - set(CONFIG_KEYS))
        if unknown:
            raise UsageError(f"{CONFIG_FILE} has unknown keys {', '.join(unknown)}; the known keys are {', '.join(CONFIG_KEYS)}")
    merged = {**registry.defaults, **values}
    if "bytes_per_token" not in values and os.environ.get(BYTES_PER_TOKEN_VARIABLE):
        merged["bytes_per_token"] = os.environ[BYTES_PER_TOKEN_VARIABLE]
    try:
        bytes_per_token = positive_ratio(merged["bytes_per_token"])
    except argparse.ArgumentTypeError as error:
        raise UsageError(f"bytes_per_token: {error}")
    return Config(
        targets=config_targets(registry, values["targets"]) if "targets" in values else detected_targets(root, registry),
        rules_dir=config_path("rules_dir", merged["rules_dir"]),
        skills_dir=config_path("skills_dir", merged["skills_dir"]),
        docs_dir=config_path("docs_dir", merged["docs_dir"]),
        docs_index=config_path("docs_index", merged["docs_index"]),
        rule_line_limit=config_count("rule_line_limit", merged["rule_line_limit"]),
        token_budget=config_count("token_budget", merged["token_budget"], allow_none=True),
        bytes_per_token=bytes_per_token,
        agents_md_max_bytes=config_count("agents_md_max_bytes", merged["agents_md_max_bytes"]),
        from_file=path.is_file(),
    )


