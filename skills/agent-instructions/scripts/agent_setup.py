def missing_markers_problem(root: Path, keys: dict, configs: List[str], entries: List[Tuple[str, str]], config: Config) -> Problem:
    typescript = keys.get("typescript_config")
    schema = keys.get("schema")
    if configs:
        where = f"under knowledge_base.code_guidelines.filePatterns in {configs[0]}, merging with the keys already there"
    elif typescript and os.path.lexists(root / typescript):
        where = f"in a YAML file under .coderabbit/ that {typescript} imports into knowledge_base.code_guidelines.filePatterns (a .coderabbit.yaml would replace the TypeScript config)"
    else:
        where = f"in a new {keys.get('config_files', ['.coderabbit.yaml'])[0]}" + (f" that starts with # yaml-language-server: $schema={schema}" if schema else "")
    return Problem(
        f"no CodeRabbit config holds the `{CODERABBIT_BEGIN}` and `{CODERABBIT_END}` lines: run {GENERATE_COMMAND} to print the block to paste.",
        f"Paste this {where}, then run {GENERATE_COMMAND} again:\n{coderabbit_snippet(entries, config)}",
    )


def plan_coderabbit(root: Path, target: RuleTarget, rules: List[Rule], config: Config, plan: GenerationPlan) -> None:
    keys = target.keys
    entries = coderabbit_entries(rules, keys)
    configs, fragments = coderabbit_files(root, keys)
    holders = [name for name in configs + fragments if holds_markers(read_text(root / name))]
    if not holders:
        plan.problems.append(missing_markers_problem(root, keys, configs, entries, config))
        return
    if len(holders) > 1:
        plan.problems.append(Problem(f"{' and '.join(holders)} all hold agent-setup markers: keep the block in one file."))
        return
    holder = holders[0]
    plan.outputs.append(holder)
    text = read_text(root / holder)
    located = locate_coderabbit_block(text, full_path=holder in configs)
    if isinstance(located, str):
        plan.problems.append(Problem(
            f"{holder} {located}: run {GENERATE_COMMAND} to print the block to paste.",
            f"Paste this under knowledge_base.code_guidelines.filePatterns in {holder}, merging with the keys already there, then run {GENERATE_COMMAND} again:\n{coderabbit_snippet(entries, config)}",
        ))
        return
    begin, end, indent = located
    newline = "\r\n" if "\r\n" in text else "\n"
    lines = text.splitlines(keepends=True)
    replaced = "".join(lines[:begin + 1] + [line + newline for line in coderabbit_items(entries, indent)] + lines[end:])
    if replaced != text:
        plan.changes.append(Change("update", holder, replaced, config.rules_dir))


def apply_changes(root: Path, changes: List[Change]) -> None:
    for change in changes:
        path = root / change.path
        if change.action == "delete":
            path.unlink()
        else:
            write_file(path, change.content or "")


def change_line(change: Change) -> str:
    if change.action == "delete":
        return f"{change.path} (generated from {change.source}, which is gone)"
    return f"{change.path} (from {change.source})"


def generation_finding(change: Change) -> str:
    if change.action == "create":
        return f"{change.path} is missing for {change.source}: run {GENERATE_COMMAND} and commit the result."
    if change.action == "update":
        return f"{change.path} is out of date with {change.source}: run {GENERATE_COMMAND} and commit the result."
    return f"{change.path} was generated from {change.source}, which no longer exists: run {GENERATE_COMMAND} and commit the deletion."


def claude_md_state(root: Path) -> str:
    claude = root / "CLAUDE.md"
    if claude.is_symlink():
        agents = root / "AGENTS.md"
        return "symlink-to-agents" if agents.exists() and claude.resolve() == agents.resolve() else "symlink-elsewhere"
    if not claude.exists():
        return "absent"
    lines = read_text(claude).lstrip("\ufeff").splitlines()
    if lines and lines[0].strip() == CLAUDE_IMPORT:
        return "imports-agents"
    if any(line.strip() == CLAUDE_IMPORT for line in lines):
        return "import-not-first"
    return "other-content"


CLAUDE_MD_DESCRIPTIONS = {
    "absent": "absent",
    "imports-agents": "line 1 is @AGENTS.md",
    "symlink-to-agents": "a symlink to AGENTS.md; make it a file whose line 1 is @AGENTS.md",
    "symlink-elsewhere": "a symlink to another file",
    "import-not-first": "imports AGENTS.md, but not on line 1",
    "other-content": "holds its own instructions; merge them into AGENTS.md or docs/, then make line 1 @AGENTS.md",
}


def claude_md_first_line(root: Path) -> str:
    lines = read_text(root / "CLAUDE.md").lstrip("\ufeff").splitlines()
    return lines[0].strip() if lines else ""


def instruction_file_findings(root: Path, config: Config) -> List[str]:
    findings = []
    state = claude_md_state(root)
    if state == "absent" and ALWAYS_TARGETED in config.targets:
        findings.append(f"CLAUDE.md is missing: create it with @AGENTS.md on line 1 ({LAYOUT_COMMAND} does), because Claude Code reads AGENTS.md by itself only while no CLAUDE.md or CLAUDE.local.md exists here or in a parent directory.")
    elif state == "symlink-to-agents":
        findings.append(f"CLAUDE.md is a symlink to AGENTS.md: replace it with a file whose line 1 is @AGENTS.md ({LAYOUT_COMMAND} does); a symlink leaves no room for Claude-only lines and breaks on Windows checkouts.")
    elif state == "symlink-elsewhere":
        findings.append(f"CLAUDE.md is a symlink to {os.readlink(root / 'CLAUDE.md')}: make it a file whose line 1 is @AGENTS.md, with that file's instructions moved into AGENTS.md or docs/.")
    elif state in ("import-not-first", "other-content"):
        findings.append(f"line 1 of CLAUDE.md is {claude_md_first_line(root)!r}, not @AGENTS.md: move its content into AGENTS.md or docs/, then make line 1 @AGENTS.md.")
    if not os.path.lexists(root / "AGENTS.md"):
        findings.append(f"AGENTS.md is missing: create it ({LAYOUT_COMMAND} writes a skeleton); it is the one file nearly every agent reads.")
    return findings


def claude_links(tools: List[Tool], config: Config, owned: List[str]) -> List[Tuple[str, str]]:
    links = []
    for tool in tools:
        if tool.rules is None or tool.rules.format != LINK_FORMAT:
            continue
        links.append((tool.rules.directory, config.rules_dir))
        links.extend((directory, config.skills_dir) for directory in tool.skills_dirs)
    return unique((link, target) for link, target in links if link and link != target and not is_owned(link, owned))


def link_expectation(link: str, target: str) -> str:
    return posixpath.relpath(target, posixpath.dirname(link) or ".")


def link_state(root: Path, link: str, target: str) -> Tuple[str, str]:
    path = root / link
    expected = link_expectation(link, target)
    if path.is_symlink():
        actual = os.readlink(path).rstrip("/")
        return ("ok" if actual == expected else "elsewhere"), actual
    if path.is_dir():
        return "directory", ""
    if os.path.lexists(path):
        return "file", ""
    return "missing", ""


def link_findings(root: Path, registry: Registry, config: Config) -> List[str]:
    findings = []
    for link, target in claude_links(target_tools(registry, config), config, owned_paths(root, registry)):
        state, actual = link_state(root, link, target)
        expected = link_expectation(link, target)
        if state == "missing":
            findings.append(f"{link} is missing: make it a symlink to {expected} ({LAYOUT_COMMAND} does), so Claude Code reads {target}.")
        elif state == "directory":
            findings.append(f"{link} is a real directory: move its files into {target}, delete it, then run {LAYOUT_COMMAND} to link it to {expected}.")
        elif state == "file":
            findings.append(f"{link} is a file: replace it with a symlink to {expected}.")
        elif state == "elsewhere":
            findings.append(f"{link} points to {actual}, not {expected}: relink it with ln -sfn {expected} {link}.")
    return findings


def rule_findings(rules: List[Rule], subdirectories: List[str], files: List[str], config: Config) -> List[str]:
    findings = [f"{directory} is a subdirectory: move its rules to the top of {config.rules_dir}, the only level every tool reads." for directory in subdirectories]
    for rule in rules:
        if rule.owned:
            continue
        if rule.line_count > config.rule_line_limit:
            findings.append(f"{rule.source} has {rule.line_count} lines, over the {config.rule_line_limit}-line limit: keep the trap, its reason and a link, and move the explanation to docs/.")
        if rule.error:
            findings.append(rule_error_message(rule))
            continue
        if not rule.has_paths:
            findings.append(f"{rule.source} has no paths: frontmatter, so it loads in every session: scope it to the files it is about, or move the line into AGENTS.md.")
            continue
        for pattern in rule.globs:
            if not glob_matches_any(pattern, files):
                findings.append(f"{rule.source}: the glob {pattern} matches no file in the repository: point it at the files the rule is about, or delete the rule.")
    return findings


def files_with_checked_links(files: List[str], config: Config) -> List[str]:
    def checked(name: str) -> bool:
        if name in ("AGENTS.md", "CLAUDE.md") or name.endswith("/AGENTS.md"):
            return True
        return name.endswith(".md") and (name.startswith(config.rules_dir + "/") or name.startswith(config.docs_dir + "/"))
    return [name for name in files if checked(name)]


def markdown_link_findings(root: Path, files: List[str]) -> List[str]:
    findings, anchor_cache = [], {}
    for source in files:
        path = root / source
        if not path.is_file():
            continue
        for target in link_targets(read_text(path)):
            if EXTERNAL_TARGET.match(target):
                continue
            path_part, _, anchor = target.partition("#")
            path_part = unquote(path_part.split("?", 1)[0])
            resolved = source if not path_part else resolve_link(source, path_part)
            if resolved is None:
                findings.append(f"{source} links to {target}, which points outside the repository: link to a file inside it, or use a full URL.")
                continue
            if not (root / resolved).exists():
                findings.append(f"{source} links to {target}, which does not exist: fix the path (it is relative to {source}) or remove the link.")
                continue
            if anchor and resolved.endswith(".md") and (root / resolved).is_file():
                if resolved not in anchor_cache:
                    anchor_cache[resolved] = markdown_anchors(read_text(root / resolved))
                if unquote(anchor).lower() not in anchor_cache[resolved]:
                    findings.append(f"{source} links to {target}, but {resolved} has no heading with the anchor #{anchor}: link to an existing heading.")
    return findings


def docs_index_findings(root: Path, files: List[str], config: Config) -> List[str]:
    index = config.docs_index
    if not (root / index).is_file():
        return []
    linked = set()
    for target in link_targets(read_text(root / index)):
        if EXTERNAL_TARGET.match(target):
            continue
        path_part = unquote(target.partition("#")[0].split("?", 1)[0])
        resolved = resolve_link(index, path_part) if path_part else None
        if resolved:
            linked.add(resolved.rstrip("/"))
    prefix = config.docs_dir + "/"
    findings = []
    for name in files:
        if not name.startswith(prefix) or not name.endswith(".md") or name == index:
            continue
        if not reachable_from_index(name, linked, config.docs_dir):
            findings.append(f"{name} is not linked from {index}: add a row for it under its subject, so agents starting at the index find it.")
    return findings


def reachable_from_index(name: str, linked: set, docs_dir: str) -> bool:
    if name in linked:
        return True
    directory = posixpath.dirname(name)
    while directory and directory != docs_dir and directory != ".":
        if directory in linked or f"{directory}/README.md" in linked or f"{directory}/index.md" in linked:
            return True
        directory = posixpath.dirname(directory)
    return False


def import_names(text: str) -> List[str]:
    prose = masked_code(HTML_COMMENT.sub("", text))
    return [match.group(1).rstrip(".,;:") for match in IMPORT_REFERENCE.finditer(prose)]


def display_path(root: Path, path: Path) -> str:
    try:
        return path.relative_to(root).as_posix()
    except ValueError:
        return str(path)


def always_loaded(root: Path, rules: List[Rule]) -> AlwaysLoaded:
    seen, files, missing = set(), [], []

    def visit(path: Path, depth: int) -> None:
        if not path.is_file():
            return
        real = path.resolve()
        if real in seen:
            return
        seen.add(real)
        text = read_text(path)
        name = display_path(root, path) + (f" -> {os.readlink(path)}" if path.is_symlink() else "")
        files.append((name, len(text.encode("utf-8"))))
        if depth >= MAX_IMPORT_DEPTH:
            return
        for name in import_names(text):
            target = path.parent / name
            if target.is_file():
                visit(target, depth + 1)
            elif name.endswith((".md", ".mdc", ".txt")):
                missing.append(f"{display_path(root, path)} imports @{name}, which does not exist: fix the path or remove the import.")

    for name in ALWAYS_LOADED_FILES:
        visit(root / name, 0)
    for rule in rules:
        if not rule.has_paths:
            visit(root / rule.source, 0)
    return AlwaysLoaded(files, unique(missing))


def budget_findings(loaded: AlwaysLoaded, config: Config) -> List[str]:
    tokens = loaded.tokens(config.bytes_per_token)
    if config.token_budget is None or tokens <= config.token_budget:
        return []
    return [f"every session loads about {tokens} tokens ({loaded.total_bytes} bytes / {config.bytes_per_token}), over the token_budget of {config.token_budget} in {CONFIG_FILE}: move knowledge to docs/ or scope it with a path rule; raise the budget only in a reviewed change."]


def agents_size_findings(root: Path, config: Config) -> List[str]:
    path = root / "AGENTS.md"
    if not path.is_file():
        return []
    size = path.stat().st_size
    if size <= config.agents_md_max_bytes:
        return []
    return [f"AGENTS.md is {size} bytes, over the {config.agents_md_max_bytes}-byte cap (Codex stops reading at 32 KiB): move knowledge to docs/ and leave pointer rows."]


def tracking_findings(root: Path, paths: List[str]) -> List[str]:
    present = [path for path in unique(paths) if os.path.lexists(root / path)]
    if not present or not inside_git_checkout(root):
        return []
    try:
        completed = subprocess.run(
            ["git", "-C", str(root), "status", "--porcelain", "--ignored", "--untracked-files=all", "--", *present],
            capture_output=True,
            text=True,
            check=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return []
    findings = []
    for line in completed.stdout.splitlines():
        status, name = line[:2], line[3:]
        if status == "??":
            findings.append(f"{name} is not in git: git add it, or a clean checkout and CI will not have it.")
        elif status == "!!":
            findings.append(f"{name} is ignored by .gitignore: allowlist it ({LAYOUT_COMMAND} does for .ai and .claude), or a clean checkout and CI will not have it.")
    return findings


def check_findings(root: Path, registry: Registry, config: Config) -> Tuple[List[str], AlwaysLoaded]:
    files, _ = repository_files(root, registry)
    rules, subdirectories = read_rules(root, config.rules_dir, owned_paths(root, registry))
    plan = plan_generation(root, registry, config, rules)
    loaded = always_loaded(root, rules)
    links = [link for link, _ in claude_links(target_tools(registry, config), config, owned_paths(root, registry))]
    findings = (
        instruction_file_findings(root, config)
        + link_findings(root, registry, config)
        + [generation_finding(change) for change in plan.changes]
        + [problem.message for problem in plan.problems]
        + rule_findings(rules, subdirectories, files, config)
        + markdown_link_findings(root, files_with_checked_links(files, config))
        + docs_index_findings(root, files, config)
        + loaded.missing_imports
        + budget_findings(loaded, config)
        + agents_size_findings(root, config)
        + tracking_findings(root, [CONFIG_FILE, "AGENTS.md", "CLAUDE.md", config.rules_dir, *links, *plan.outputs])
    )
    return unique(findings), loaded


def projected_loaded_bytes(root: Path, registry: Registry, config: Config) -> int:
    rules, _ = read_rules(root, config.rules_dir, owned_paths(root, registry))
    total = always_loaded(root, rules).total_bytes
    if not os.path.lexists(root / "AGENTS.md"):
        total += len(agents_skeleton(config).encode("utf-8"))
    if claude_md_state(root) in ("absent", "symlink-to-agents"):
        total += len((CLAUDE_IMPORT + "\n").encode("utf-8"))
    return total


def measured_token_budget(tokens: int) -> int:
    with_headroom = -(-tokens * (100 + BUDGET_HEADROOM_PERCENT) // (100 * BUDGET_STEP)) * BUDGET_STEP
    return max(BUDGET_STEP, with_headroom)


def layout_config(root: Path, registry: Registry, declared: Optional[str]) -> Tuple[Config, str]:
    config = load_config(root, registry)
    if config.from_file:
        return config, ""
    if declared is not None:
        names = [name.strip() for name in declared.split(",") if name.strip()]
        for name in names:
            registry.tool(name)
        config = replace(config, targets=unique([ALWAYS_TARGETED] + names))
    loaded_bytes = projected_loaded_bytes(root, registry, config)
    tokens = round(loaded_bytes / config.bytes_per_token)
    budget = measured_token_budget(tokens)
    derivation = f"token_budget {budget}: every session will load about {tokens} tokens ({loaded_bytes} bytes / {config.bytes_per_token}), plus {BUDGET_HEADROOM_PERCENT}%, rounded up to the next {BUDGET_STEP}"
    return replace(config, token_budget=budget), derivation


