def split_top_level(text: str, quotes: bool) -> List[str]:
    parts, current, depth, quote, index = [], [], 0, None, 0
    while index < len(text):
        character = text[index]
        if quote:
            current.append(character)
            if character == "\\" and quote == '"' and index + 1 < len(text):
                current.append(text[index + 1])
                index += 2
                continue
            if character == quote:
                quote = None
        elif quotes and character in "\"'":
            quote = character
            current.append(character)
        elif character == "\\" and index + 1 < len(text):
            current.append(text[index:index + 2])
            index += 2
            continue
        elif character in "{[":
            depth += 1
            current.append(character)
        elif character in "}]":
            depth -= 1
            current.append(character)
        elif character == "," and depth <= 0:
            parts.append("".join(current))
            current = []
        else:
            current.append(character)
        index += 1
    parts.append("".join(current))
    return parts


def matching_brace(pattern: str, opening: int) -> Optional[int]:
    depth, index = 0, opening
    while index < len(pattern):
        character = pattern[index]
        if character == "\\":
            index += 2
            continue
        if character == "{":
            depth += 1
        elif character == "}":
            depth -= 1
            if depth == 0:
                return index
        index += 1
    return None


def expandable_brace(pattern: str) -> Optional[Tuple[int, int, List[str]]]:
    index = 0
    while index < len(pattern):
        if pattern[index] == "\\":
            index += 2
            continue
        if pattern[index] == "{":
            closing = matching_brace(pattern, index)
            if closing is not None:
                options = split_top_level(pattern[index + 1:closing], quotes=False)
                if len(options) > 1:
                    return index, closing, options
        index += 1
    return None


def expand_braces(pattern: str) -> List[str]:
    group = expandable_brace(pattern)
    if group is None:
        return [pattern]
    opening, closing, options = group
    expanded = []
    for option in options:
        for candidate in expand_braces(pattern[:opening] + option + pattern[closing + 1:]):
            if candidate not in expanded:
                expanded.append(candidate)
            if len(expanded) > MAX_GLOB_EXPANSIONS:
                raise FrontmatterError(f"the glob {pattern} expands to more than {MAX_GLOB_EXPANSIONS} patterns")
    return expanded


def character_class_end(pattern: str, opening: int) -> Optional[int]:
    index = opening + 1
    if index < len(pattern) and pattern[index] in "!^":
        index += 1
    if index < len(pattern) and pattern[index] == "]":
        index += 1
    closing = pattern.find("]", index)
    return closing if closing != -1 else None


def character_class(content: str) -> str:
    negated = content[:1] in ("!", "^")
    members = (content[1:] if negated else content).replace("\\", "\\\\")
    return f"[^/{members}]" if negated else f"[{members}]"


def glob_to_regex(pattern: str) -> re.Pattern:
    pattern = pattern[1:] if pattern.startswith("/") else pattern
    if pattern.endswith("/"):
        pattern += "**"
    parts, index, length = [], 0, len(pattern)
    while index < length:
        character = pattern[index]
        if character == "\\" and index + 1 < length:
            parts.append(re.escape(pattern[index + 1]))
            index += 2
            continue
        if character == "*":
            end = index
            while end < length and pattern[end] == "*":
                end += 1
            whole_segment = (index == 0 or pattern[index - 1] == "/") and (end == length or pattern[end] == "/")
            if end - index >= 2 and whole_segment:
                parts.append(".*" if end == length else "(?:.*/)?")
                end += 0 if end == length else 1
            else:
                parts.append("[^/]*")
            index = end
            continue
        if character == "?":
            parts.append("[^/]")
            index += 1
            continue
        if character == "[":
            closing = character_class_end(pattern, index)
            if closing is not None:
                parts.append(character_class(pattern[index + 1:closing]))
                index = closing + 1
                continue
        parts.append(re.escape(character))
        index += 1
    return re.compile(r"\A" + "".join(parts) + r"\Z")


def glob_matches_any(pattern: str, files: List[str]) -> bool:
    expressions = [glob_to_regex(candidate) for candidate in expand_braces(pattern)]
    return any(expression.match(name) for name in files for expression in expressions)


