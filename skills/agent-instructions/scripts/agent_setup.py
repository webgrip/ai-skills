def directory_step(root: Path, relative: str, purpose: str) -> Step:
    path = root / relative
    if path.is_dir():
        return Step("keep", relative + "/", purpose)
    if os.path.lexists(path):
        return Step("manual", relative, f"is a file, but {purpose} needs a directory here")
