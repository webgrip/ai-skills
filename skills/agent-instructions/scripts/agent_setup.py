def skills_steps(root: Path, registry: Registry, config: Config) -> List[Step]:
    generators = [tool for tool in registry.in_categories(("generator",)) if tool.skills_dirs and tool_evidence(root, tool)]
    if not generators:
        return [directory_step(root, config.skills_dir, "the one skills directory")]
    steps = [directory_step(root, directory, f"hand-written skills that {tool.name} copies into {config.skills_dir}") for tool in generators for directory in tool.skills_dirs]
    if not (root / config.skills_dir).exists():
        steps.append(Step("note", config.skills_dir, f"is generated by {', '.join(tool.name for tool in generators)}; run its install command to fill it"))
    return steps


def make_symlink(path: Path, target: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    os.symlink(target, path)


def link_steps(root: Path, registry: Registry, config: Config) -> List[Step]:
    steps = []
    for link, target in claude_links(target_tools(registry, config), config, owned_paths(root, registry)):
        state, actual = link_state(root, link, target)
        expected = link_expectation(link, target)
        path = root / link
        if state == "ok":
            steps.append(Step("keep", link, f"-> {expected}"))
        elif state == "missing":
            steps.append(Step("link", link, f"-> {expected}", lambda path=path, expected=expected: make_symlink(path, expected)))
        elif state == "directory":
            steps.append(Step("manual", link, f"is a real directory, which layout never replaces: move its contents into {target}, delete it, then run layout again"))
        elif state == "file":
            steps.append(Step("manual", link, f"is a file: remove it, then run layout again to link it to {expected}"))
        else:
            steps.append(Step("manual", link, f"points to {actual}, not {expected}: remove it, then run layout again"))
    return steps


def gitignore_update(original: str) -> Tuple[str, List[str]]:
    newline = "\r\n" if "\r\n" in original else "\n"
    lines = original.splitlines()
    changes = []
    for directory, entries in GITIGNORE_ALLOWLISTS:
        wholesale = {variant for name in (directory, "/" + directory) for variant in (name, name + "/", name + "/**")}
        star = {directory + "/*", "/" + directory + "/*"}
        position = next((index for index, line in enumerate(lines) if line.strip() in wholesale), None)
        if position is not None:
            changes.append(f"replace {lines[position].strip()} with an allowlist under {directory}/*")
            lines[position] = directory + "/*"
        else:
            position = next((index for index, line in enumerate(lines) if line.strip() in star), None)
            if position is None:
                continue
        present = {line.strip() for line in lines}
        missing = [f"!{directory}/{entry}" for entry in entries if f"!{directory}/{entry}" not in present and f"!/{directory}/{entry}" not in present]
        if missing:
            lines[position + 1:position + 1] = missing
            changes.append(f"allow {', '.join(missing)}")
    present = {line.strip().lstrip("/") for line in lines}
    added = [entry for entry in GITIGNORE_ENTRIES if entry not in present]
    if added:
        lines.extend(added)
        changes.append(f"ignore {', '.join(added)}")
    return newline.join(lines) + newline, changes


def gitignore_step(root: Path) -> Step:
    path = root / ".gitignore"
    updated, changes = gitignore_update(read_text(path) if path.is_file() else "")
    if not changes:
        return Step("keep", ".gitignore", "has the agent entries")
    return Step("update" if path.exists() else "create", ".gitignore", "; ".join(changes), lambda: write_file(path, updated))


def plan_layout(root: Path, registry: Registry, config: Config, declared: Optional[str], budget_derivation: str) -> List[Step]:
    return [
        config_step(root, config, declared, budget_derivation),
        agents_step(root, config),
        claude_step(root),
        docs_index_step(root, config),
        directory_step(root, config.rules_dir, "the one rules source"),
        *skills_steps(root, registry, config),
        *link_steps(root, registry, config),
        gitignore_step(root),
    ]


def describe_file(root: Path, name: str, nested: bool) -> Optional[dict]:
    path = root / name
    if path.is_dir() and not path.is_symlink():
        return None
    entry = {"path": name, "nested": nested}
    if path.is_symlink():
        entry["symlink_to"] = os.readlink(path)
    if path.is_file():
        text = read_text(path)
        entry["bytes"] = len(text.encode("utf-8"))
        entry["lines"] = len(text.splitlines())
    return entry


def instruction_files(root: Path, registry: Registry, files: List[str]) -> List[dict]:
    names = unique(name for tool in registry.tools for name in tool.instructions)
    entries = [entry for entry in (describe_file(root, name, False) for name in names if os.path.lexists(root / name)) if entry]
    listed = {entry["path"] for entry in entries}
    nested = [name for name in files if "/" in name and posixpath.basename(name) in registry.nested_instruction_names and name not in listed]
    return entries + [entry for entry in (describe_file(root, name, True) for name in nested) if entry]


def count_files(path: Path, extensions: Tuple[str, ...]) -> int:
    if path.is_file():
        return 1
    return sum(1 for _, _, names in os.walk(path) for name in names if name.endswith(extensions))


def directory_entry(root: Path, name: str) -> dict:
    path = root / name
    entry = {"path": name}
    if path.is_symlink():
        entry["symlink_to"] = os.readlink(path)
    entry["kind"] = "directory" if path.is_dir() else "file"
    return entry


def path_rule_directories(root: Path, registry: Registry, config: Config) -> List[dict]:
    names = unique([config.rules_dir] + [name for tool in registry.tools if tool.rules for name in (tool.rules.directory, *tool.rules.also_directories) if name])
    entries = []
    for name in names:
        if os.path.lexists(root / name):
            entry = directory_entry(root, name)
            entry["files"] = count_files(root / name, (".md", ".mdc"))
            entries.append(entry)
    return entries


def skills_directories(root: Path, registry: Registry, config: Config) -> List[dict]:
    names = unique([config.skills_dir] + [name for tool in registry.tools for name in tool.skills_dirs])
    entries = []
    for name in names:
        path = root / name
        if os.path.lexists(path):
            entry = directory_entry(root, name)
            entry["skills"] = sum(1 for child in path.iterdir() if (child / "SKILL.md").is_file()) if path.is_dir() else 0
            entries.append(entry)
    return entries


def evidence_rows(registry: Registry, evidence: dict, categories) -> List[dict]:
    return [{"tool": tool.id, "name": tool.name, "evidence": evidence[tool.id]} for tool in registry.in_categories(categories) if evidence[tool.id]]


def existing_paths(root: Path, names) -> List[str]:
    return [name for name in unique(names) if detect_entry(root, name)]


def tool_files(root: Path, tools: List[Tool], attribute: str) -> List[dict]:
    rows = []
    for tool in tools:
        for name in getattr(tool, attribute):
            for match in detect_entry(root, name):
                rows.append({"tool": tool.id, "path": match})
    return rows


def shared_hook_notes(root: Path, tools: List[Tool]) -> List[str]:
    notes = []
    for reader in tools:
        for owner in tools:
            if owner.id == reader.id:
                continue
            shared = [name for name in reader.reads_hooks_from if name in owner.hooks_files]
            if not shared:
                continue
            present = [name for name in shared if os.path.lexists(root / name)]
            state = f"{', '.join(present)} exists" if present else "no such file yet"
            notes.append(f"{reader.name} also runs {owner.name}'s hooks from {' and '.join(shared)} ({state}): write each hook so it is safe in both tools, or turn that reading off in {reader.name}.")
    return notes


def tool_notes(registry: Registry, evidence: dict) -> List[str]:
    notes = []
    for tool in registry.tools:
        if not evidence[tool.id]:
            continue
        if tool.note:
            notes.append(f"{tool.name}: {tool.note}")
        if tool.owns:
            notes.append(f"{tool.name} manages {', '.join(tool.owns)}; agent_setup.py leaves them to it.")
    return notes


def flagged_file_notes(root: Path, registry: Registry) -> List[str]:
    notes = []
    for name in registry.flagged_files:
        if os.path.lexists(root / name):
            readers = [tool.name for tool in registry.tools if name in tool.instructions]
            notes.append(f"{name} is present: {', '.join(readers)} read it; every other tool ignores it, so keep shared rules in AGENTS.md.")
    return notes


def inventory_report(root: Path, registry: Registry, config: Config) -> dict:
    files, listing = repository_files(root, registry)
    rules, _ = read_rules(root, config.rules_dir, owned_paths(root, registry))
    evidence = {tool.id: tool_evidence(root, tool) for tool in registry.tools}
    loaded = always_loaded(root, rules)
    claude = [registry.tool(ALWAYS_TARGETED)]
    targets = target_tools(registry, config)
    return {
        "root": str(root),
        "file_listing": listing,
        "agents_detected": [tool.id for tool in registry.in_categories(TARGET_CATEGORIES) if evidence[tool.id]],
        "targets": config.targets,
        "targets_from": CONFIG_FILE if config.from_file else "detection",
        "instruction_files": instruction_files(root, registry, files),
        "claude_md": claude_md_state(root),
        "path_rule_dirs": path_rule_directories(root, registry, config),
        "skills_dirs": skills_directories(root, registry, config),
        "mcp_configs": existing_paths(root, (name for tool in registry.tools for name in tool.mcp_configs)),
        "ignore_files": existing_paths(root, (name for tool in registry.tools for name in tool.ignore_files)),
        "hooks_files": tool_files(root, list(registry.tools), "hooks_files"),
        "review_bots": evidence_rows(registry, evidence, ("review-bot",)),
        "cloud_agent_setup": tool_files(root, list(registry.tools), "setup_files"),
        "generators": evidence_rows(registry, evidence, ("generator",)),
        "ci": evidence_rows(registry, evidence, ("ci",)),
        "hook_managers": evidence_rows(registry, evidence, ("hook-manager",)),
        "docs": {
            "dir": config.docs_dir if (root / config.docs_dir).is_dir() else None,
            "index": config.docs_index if (root / config.docs_index).is_file() else None,
            "sites": existing_paths(root, registry.docs_sites),
        },
        "symlinks": [
            {"path": link, "expected": link_expectation(link, target), "state": state, "points_to": actual or None}
            for link, target in claude_links(claude, config, owned_paths(root, registry))
            for state, actual in [link_state(root, link, target)]
        ],
        "always_loaded": {
            "bytes": loaded.total_bytes,
            "tokens": loaded.tokens(config.bytes_per_token),
            "bytes_per_token": config.bytes_per_token,
            "files": [name for name, _ in loaded.files],
        },
        "notes": shared_hook_notes(root, targets) + tool_notes(registry, evidence) + flagged_file_notes(root, registry),
    }


def joined_or_none(values: List[str]) -> str:
    return ", ".join(values) if values else "none"


def evidence_label(row: dict) -> str:
    return f"{row['name']} ({joined_or_none(row['evidence'])})"


def print_inventory(report: dict) -> None:
    print(f"Repository: {report['root']} (files from {report['file_listing']})")
    print(f"Agents detected: {joined_or_none(report['agents_detected'])}")
    print(f"Targets ({report['targets_from']}): {joined_or_none(report['targets'])}")
    print("Instruction files:" + ("" if report["instruction_files"] else " none"))
    for entry in report["instruction_files"]:
        detail = f"-> {entry['symlink_to']}" if "symlink_to" in entry else f"{entry.get('bytes', 0)} bytes, {entry.get('lines', 0)} lines"
        print(f"  {entry['path']}{' (nested)' if entry['nested'] else ''}  {detail}")
    print(f"CLAUDE.md: {CLAUDE_MD_DESCRIPTIONS[report['claude_md']]}")

    def directories(entries: List[dict], unit: str) -> str:
        return joined_or_none([f"{entry['path']} -> {entry['symlink_to']}" if "symlink_to" in entry else f"{entry['path']} ({entry[unit]} {unit})" for entry in entries])

    print(f"Path rules: {directories(report['path_rule_dirs'], 'files')}")
    print(f"Skills: {directories(report['skills_dirs'], 'skills')}")
    print(f"MCP configs: {joined_or_none(report['mcp_configs'])}")
    print(f"Ignore files: {joined_or_none(report['ignore_files'])}")
    print(f"Hooks files: {joined_or_none([row['path'] for row in report['hooks_files']])}")
    for label, key in (("Review bots", "review_bots"), ("Generators", "generators"), ("CI", "ci"), ("Hook manager", "hook_managers")):
        print(f"{label}: {joined_or_none([evidence_label(row) for row in report[key]])}")
    print(f"Cloud-agent setup: {joined_or_none([row['path'] for row in report['cloud_agent_setup']])}")
    docs = report["docs"]
    print(f"Docs: {docs['dir'] or 'no docs directory'}, index {docs['index'] or 'missing'}, site {joined_or_none(docs['sites'])}")
    print("Symlinks: " + "; ".join(f"{row['path']} {row['state']}" + (f" -> {row['points_to']}" if row["points_to"] else "") + ("" if row["state"] == "ok" else f" (expected -> {row['expected']})") for row in report["symlinks"]))
    loaded = report["always_loaded"]
    print(f"Always loaded: ~{loaded['tokens']} tokens ({loaded['bytes']} bytes / {loaded['bytes_per_token']}) from {joined_or_none(loaded['files'])}")
    for note in report["notes"]:
        print(f"Note: {note}")


def run_inventory(arguments) -> int:
    root, registry = resolve_root(arguments.repo), resolve_registry(arguments.registry)
    config = load_config(root, registry)
    if arguments.bytes_per_token:
        config = replace(config, bytes_per_token=arguments.bytes_per_token)
    report = inventory_report(root, registry, config)
    if arguments.json:
        print(json.dumps(report, indent=2))
    else:
        print_inventory(report)
    return 0


def run_layout(arguments) -> int:
    root, registry = resolve_root(arguments.repo), resolve_registry(arguments.registry)
    config, budget_derivation = layout_config(root, registry, arguments.targets)
    steps = plan_layout(root, registry, config, arguments.targets, budget_derivation)
    print(f"{'Applied to' if arguments.apply else 'Plan for'} {root}{'' if arguments.apply else ' (dry run; --apply writes it)'}:")
    for step in steps:
        if arguments.apply and step.action:
            step.action()
        print(f"{step.status:<6}  {step.path}  {step.detail}")
    return 1 if any(step.status == "manual" for step in steps) else 0


def run_generate(arguments) -> int:
    root, registry = resolve_root(arguments.repo), resolve_registry(arguments.registry)
    config = load_config(root, registry)
    rules, _ = read_rules(root, config.rules_dir, owned_paths(root, registry))
    plan = plan_generation(root, registry, config, rules)
    blocked = any(rule.error for rule in rules if not rule.owned)
    if not arguments.check and not blocked:
        apply_changes(root, plan.changes)
    verb = "would " if arguments.check or blocked else ""
    for change in plan.changes:
        print(f"{verb}{change.action} {change_line(change)}")
    for note in plan.notes:
        print(f"note: {note}")
    for problem in plan.problems:
        print(f"FAIL: {problem.message}")
        if problem.detail and not arguments.check:
            print(problem.detail)
    if blocked:
        print("FAIL: nothing was written; fix the rules above first.")
    if not plan.changes and not plan.problems:
        print(f"{GENERATE_COMMAND}: every generated file is up to date")
    if plan.problems or blocked:
        return 1
    return 1 if arguments.check and plan.changes else 0


def run_check(arguments) -> int:
    root, registry = resolve_root(arguments.repo), resolve_registry(arguments.registry)
    config = load_config(root, registry)
    if arguments.bytes_per_token:
        config = replace(config, bytes_per_token=arguments.bytes_per_token)
    findings, loaded = check_findings(root, registry, config)
    budget = config.token_budget if config.token_budget is not None else "none"
    print(f"info: every session loads about {loaded.tokens(config.bytes_per_token)} tokens ({loaded.total_bytes} bytes / {config.bytes_per_token}; budget {budget}) from {joined_or_none([name for name, _ in loaded.files])}")
    for finding in findings:
        print(f"FAIL: {finding}")
    print(f"agent_setup.py check: {len(findings)} finding{'' if len(findings) == 1 else 's'}" if findings else "agent_setup.py check: clean")
    return 1 if findings else 0


def build_parser() -> argparse.ArgumentParser:
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("repo", nargs="?", default=".", help="repository root (default: the current directory)")
    common.add_argument("--registry", help="tool registry JSON (default: assets/targets.json beside scripts/, or targets.json next to this script)")
    ratio_help = f"bytes per token for the estimate (default: bytes_per_token in {CONFIG_FILE}, else ${BYTES_PER_TOKEN_VARIABLE}, else 2.9, measured on Markdown instruction files with claude -p /context)"
    parser = argparse.ArgumentParser(prog="agent_setup.py", description=__doc__, epilog=GLOB_DIALECT, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest="command", required=True, metavar="command")

    inventory = commands.add_parser("inventory", parents=[common], help="report what the repository has for agents", description="Report instruction files, path-rule and skills directories, MCP, ignore and hooks files, review bots, cloud-agent setup, generators, CI, hook manager, docs, the .claude symlinks and the always-loaded token estimate.")
    inventory.add_argument("--json", action="store_true", help="print the report as JSON")
    inventory.add_argument("--bytes-per-token", type=positive_ratio, help=ratio_help)
    inventory.set_defaults(handler=run_inventory)

    layout = commands.add_parser("layout", parents=[common], help="plan, or with --apply write, the canonical layout", description=f"Plan {CONFIG_FILE}, AGENTS.md, CLAUDE.md = @AGENTS.md, the docs index, the rules directory, the skills directory, the .claude/rules and .claude/skills symlinks and the .gitignore entries. A new {CONFIG_FILE} gets token_budget = what every session will load, plus {BUDGET_HEADROOM_PERCENT}%, rounded up to the next {BUDGET_STEP}. Exits 1 while a step needs a person.")
    layout.add_argument("--apply", action="store_true", help="write the plan; a second run changes nothing")
    layout.add_argument("--targets", help=f"comma-separated tool ids for a new {CONFIG_FILE} (default: the detected tools); {ALWAYS_TARGETED} is always included")
    layout.set_defaults(handler=run_layout)

    generate = commands.add_parser("generate", parents=[common], help="write each enabled tool's rule files from the rules directory", description="Generate every enabled target's path-rule files and the CodeRabbit filePatterns block from the flat rules directory, delete generated files whose rule is gone, and never overwrite a file without the generated marker.", epilog=GLOB_DIALECT, formatter_class=argparse.RawDescriptionHelpFormatter)
    generate.add_argument("--check", action="store_true", help="write nothing; exit 1 listing every file that would change")
    generate.set_defaults(handler=run_generate)

    check = commands.add_parser("check", parents=[common], help="the CI gate", description="Fail, one line per finding, on: CLAUDE.md not starting with @AGENTS.md, a missing or wrong .claude symlink, generated files out of date, a rule without paths, with a glob matching nothing, over the line limit or in a subdirectory, a broken relative link or anchor, a doc missing from the docs index, the always-loaded estimate over token_budget, AGENTS.md over its byte cap, and agent files git does not track.", epilog=GLOB_DIALECT, formatter_class=argparse.RawDescriptionHelpFormatter)
    check.add_argument("--bytes-per-token", type=positive_ratio, help=ratio_help)
    check.set_defaults(handler=run_check)
    return parser


def main(argv: Optional[List[str]] = None) -> int:
    arguments = build_parser().parse_args(argv)
    try:
        return arguments.handler(arguments)
    except UsageError as error:
        print(f"agent_setup.py: {error}", file=sys.stderr)
        return 2
    except OSError as error:
        print(f"agent_setup.py: {error.filename or ''}: {error.strerror}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
