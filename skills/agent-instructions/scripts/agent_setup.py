def claude_step(root: Path) -> Step:
    state = claude_md_state(root)
    path = root / "CLAUDE.md"
    if state == "absent":
        return Step("create", "CLAUDE.md", "line 1 is @AGENTS.md", lambda: write_file(path, CLAUDE_IMPORT + "\n"))
    if state == "imports-agents":
        return Step("keep", "CLAUDE.md", "line 1 is @AGENTS.md")
    if state == "symlink-to-agents":
        return Step("update", "CLAUDE.md", "replace the symlink to AGENTS.md with a file whose line 1 is @AGENTS.md", lambda: replace_claude_symlink(root))
    if state == "symlink-elsewhere":
        return Step("manual", "CLAUDE.md", f"is a symlink to {os.readlink(path)}: move that content into AGENTS.md or docs/, then make CLAUDE.md a file whose line 1 is @AGENTS.md")
    if state == "import-not-first":
        return Step("manual", "CLAUDE.md", "merge by hand: move the content above @AGENTS.md into AGENTS.md or docs/, then make line 1 `@AGENTS.md`")
    return Step("manual", "CLAUDE.md", "merge by hand: move its content into AGENTS.md or docs/, then make line 1 `@AGENTS.md`")


